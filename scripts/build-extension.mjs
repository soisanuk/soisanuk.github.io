// Package the browser extension out of the app.
//
// The extension is not a separate codebase — it is the trainer's tone engine,
// segmenter, dictionary and word card, loaded into somebody else's page. So
// nothing here is authored twice: the sources are copied from web/js and the
// card's styles are extracted from web/index.html, and --check fails if either
// has drifted. Hand-maintained copies of forty CSS rules and nine JS files are
// how an extension quietly stops matching the app it came from.
//
//   node scripts/build-extension.mjs           # write
//   node scripts/build-extension.mjs --check   # verify; exit 1 on drift
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";

const ROOT = new URL("..", import.meta.url).pathname;
const OUT = ROOT + "extension/";
const VENDOR = OUT + "vendor/";

// In load order. wordcard.js needs data.js (WORDS/CONSONANTS/VOWELS),
// thai-script.js and tokeniser.js; segment.js needs the lexicon to already be
// defined — declaring it as a content script means _segLoad short-circuits
// instead of trying to inject `js/lexicon-th.js`, a path that cannot resolve
// inside an extension. examples.js is optional (wordcard guards EXAMPLES) but
// carries the example sentences, which are most of why the card is good.
const SOURCES = [
  "web/js/data.js",
  "web/js/examples.js",
  "web/js/thai-script.js",
  // curriculum.js is here for ONE function: toneOfWord. It is 20KB of course
  // spine we do not otherwise need, but it is DOM-free at load and needs only
  // what is already bundled, and reimplementing its multi-syllable abstention
  // in the extension would be authoring the same rule twice.
  "web/js/curriculum.js",
  "web/js/tokeniser.js",
  "web/js/wordcard.js",
  "web/js/lexicon-th.js",
  "web/js/segment.js",
  "web/js/gloss-th.js",
  "web/js/gloss-extra.js",
  "web/js/gloss-vol.js",
  "web/js/gloss.js",
  "spike/thai-dom.js",
];

// Card styles to lift out of index.html. Prefix match on selector text.
const WANTED = [
  "#wc-overlay", ".wc-", "#script-tooltip", ".st-", "#word-tooltip", ".tt-",
  ".decomp", ".example", ".w-token", ".rtgs", ".thai-big", ".cluster",
];

const BANNER = f => `// COPIED from ${f} by scripts/build-extension.mjs — do not edit here.\n` +
  `// Edit the source and re-run the build; --check fails on drift.\n`;

function buildCss() {
  const html = readFileSync(ROOT + "web/index.html", "utf8");
  // Comments MUST go before the rule scan. The regex below treats everything
  // between one `}` and the next `{` as the selector, so a rule preceded by a
  // comment carries that comment in its selector text and fails the prefix
  // test. That silently dropped #wc-overlay, .wc-layer and #word-tooltip —
  // every rule that happened to follow a comment — which is why the card
  // rendered with no backgrounds and black text while its children looked
  // fine. The rules it kept were exactly the ones sitting directly after
  // another rule's closing brace.
  const style = html.slice(html.indexOf("<style>") + 7, html.indexOf("</style>"))
    .replace(/\/\*[\s\S]*?\*\//g, "");
  const rootBlock = style.match(/:root\s*\{[^}]*\}/);
  const rules = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(style))) {
    const sel = m[1].trim().replace(/\s+/g, " ");
    if (sel.startsWith("@") || sel.startsWith(":root")) continue;
    if (sel.split(",").some(s => WANTED.some(w => s.trim().startsWith(w)))) {
      rules.push(`${sel} {${m[2].replace(/\s+/g, " ").trimEnd()} }`);
    }
  }
  return `/* AUTO-GENERATED by scripts/build-extension.mjs — do not edit by hand.
 * The word card's styles from web/index.html, for the extension's shadow root.
 * ${rules.length} rules. Inside a shadow root these cannot reach the host page
 * and its rules cannot reach them.
 */

${rootBlock ? rootBlock[0].replace(":root", ":host") : ":host { }"}

:host { all: initial; font-family: system-ui, -apple-system, sans-serif; }

/* The base text colour has to go on the MOUNTS, not on :host.
   shell.js gives the host an inline "all:initial!important" so the page's own
   rules cannot inherit into the card — and an inline !important beats any
   :host rule we write, including a colour. So a :host colour is silently
   overridden and every element that does not name its own colour renders
   black on the dark panel. Setting it on the mounts puts it inside the
   boundary, where the host's inline style cannot reach. */
#wc-overlay, #script-tooltip, #word-tooltip, #td-credit {
  color: var(--text);
  font-family: system-ui, -apple-system, sans-serif;
  line-height: 1.4;
}

${rules.join("\n")}
`;
}

const css = buildCss();
// A content script cannot inject a <link> into a shadow root, and fetching the
// stylesheet would need web_accessible_resources plus an async boundary before
// the card can render. Shipping it as a string sidesteps both.
const cssJs = `// AUTO-GENERATED by scripts/build-extension.mjs — do not edit by hand.\n` +
  `const TD_SHELL_CSS = ${JSON.stringify(css)};\n`;

const files = { "shell.css": css, "shell-css.js": cssJs };
for (const src of SOURCES) {
  files["vendor/" + src.split("/").pop()] = BANNER(src) + readFileSync(ROOT + src, "utf8");
}

if (process.argv.includes("--check")) {
  let bad = [];
  for (const [rel, want] of Object.entries(files)) {
    let cur = null;
    try { cur = readFileSync(OUT + rel, "utf8"); } catch {}
    if (cur !== want) bad.push(rel);
  }
  // a stale vendor file nothing copies any more is drift too
  const expected = new Set(Object.keys(files).filter(f => f.startsWith("vendor/")).map(f => f.slice(7)));
  let stray = [];
  try { stray = readdirSync(VENDOR).filter(f => !expected.has(f)); } catch {}
  if (bad.length || stray.length) {
    console.error(`extension is out of date — run: node scripts/build-extension.mjs`);
    if (bad.length) console.error("  stale: " + bad.join(", "));
    if (stray.length) console.error("  orphaned: " + stray.join(", "));
    process.exit(1);
  }
  console.log(`extension in sync (${SOURCES.length} sources + styles)`);
} else {
  mkdirSync(VENDOR, { recursive: true });
  const expected = new Set(Object.keys(files).filter(f => f.startsWith("vendor/")).map(f => f.slice(7)));
  for (const f of readdirSync(VENDOR)) if (!expected.has(f)) rmSync(VENDOR + f);
  for (const [rel, body] of Object.entries(files)) writeFileSync(OUT + rel, body);
  console.log(`wrote extension/ — ${SOURCES.length} sources + shell.css (${css.split("\n").length} lines)`);
}

// Extract the word card's styles out of web/index.html into the extension's
// shadow-root stylesheet.
//
// Hand-copying 40-odd rules out of a 2,000-line <style> block is exactly the
// job that silently drifts: someone edits a .wc- rule in the app, the
// extension keeps the old one, and the card looks subtly wrong in a place
// nobody is looking. This regenerates, and --check fails on drift.
//
//   node scripts/build-extension-css.mjs           # write
//   node scripts/build-extension-css.mjs --check   # verify, exit 1 on drift
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("..", import.meta.url).pathname;
const SRC = ROOT + "web/index.html";
const OUT = ROOT + "extension/shell.css";

// Everything the card and its two tooltips render with. Prefix match on the
// selector text, so `.wc-` catches `.wc-layer`, `.wc-thai:hover` and so on.
const WANTED = [
  "#wc-overlay", ".wc-", "#script-tooltip", ".st-", "#word-tooltip", ".tt-",
  ".decomp", ".example", ".w-token", ".rtgs", ".thai-big", ".cluster",
];

const html = readFileSync(SRC, "utf8");
const style = html.slice(html.indexOf("<style>") + 7, html.indexOf("</style>"));

// The design tokens the rules reference (var(--jade) etc). Taken whole: the
// card would render with browser defaults without them.
const rootBlock = style.match(/:root\s*\{[^}]*\}/);

// A crude but sufficient rule splitter — this stylesheet has no @media nesting
// inside the parts we want, and anything it cannot parse is simply not copied.
const rules = [];
const re = /([^{}]+)\{([^{}]*)\}/g;
let m;
while ((m = re.exec(style))) {
  const sel = m[1].trim().replace(/\s+/g, " ");
  if (sel.startsWith("@") || sel.startsWith(":root")) continue;
  const keep = sel.split(",").some(s => WANTED.some(w => s.trim().startsWith(w)));
  if (keep) rules.push(`${sel} {${m[2].replace(/\s+/g, " ").trimEnd()} }`);
}

const out = `/* AUTO-GENERATED by scripts/build-extension-css.mjs — do not edit by hand.
 *
 * The word card's styles, lifted out of web/index.html for the extension's
 * shadow root. Inside a shadow root these cannot reach the host page and the
 * host page's rules cannot reach them, which is the whole reason the card
 * renders there rather than in the document.
 *
 * ${rules.length} rules. Regenerate after editing card styles in index.html.
 */

/* Design tokens the rules below reference. */
${rootBlock ? rootBlock[0].replace(":root", ":host") : ":host { }"}

/* The card lives on top of somebody else's page. */
:host {
  all: initial;
  font-family: system-ui, -apple-system, sans-serif;
}

${rules.join("\n")}
`;

if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(OUT, "utf8"); } catch {}
  if (cur !== out) {
    console.error("extension/shell.css is out of date — run: node scripts/build-extension-css.mjs");
    process.exit(1);
  }
  console.log(`extension/shell.css in sync (${rules.length} rules)`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote extension/shell.css — ${rules.length} rules`);
}

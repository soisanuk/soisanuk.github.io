// Build web/js/seg-phrases.js — lexicon entries that are PHRASES, not words.
//
//   node scripts/build-seg-phrases.mjs <VISTEC-TP-TH-2021_train_proprocessed.txt>
//
// SOURCE: VISTEC-TP-TH-2021, Limkonchotiwat et al. (ACL-IJCNLP 2021) —
// https://github.com/mrpeerat/OSKut/tree/main/VISTEC-TP-TH-2021 — 49,997
// sentences of Thai social media, word boundaries annotated by linguists,
// licensed CC BY-SA 3.0. The corpus is a download, not checked in, exactly
// like the kaikki dump and the Volubilis workbook.
//
// WHY THIS EXISTS. lexicon-th.js is a frequency-ordered word list, and the
// segmenter's cost is a unigram model: one token always beats two when the
// compound exists at all. So any PHRASE that happens to be in the list wins
// against its own parts. ฝนตกหนัก parsed as ฝน|ตกหนัก and glossed "shoulder a
// burden" — ตกหนัก is in the list at rank 6792 and costs less than ตก + หนัก.
//
// No cost tweak fixes that. Measured three ways before writing this: a
// per-token cost was tried and rejected once already (docs/persona-playtests.md
// records it altering 7 of 940 sentences and getting 3 wrong); a rank-based PMI
// proxy does not separate the classes (lexicalised −1.30..5.99, compositional
// −2.88..4.20, total overlap); and a rarity ratio flags 1,737 entries including
// วันนี้ and ที่อยู่. The distinction is about CONTEXT, and rank order carries
// no context. Human annotation does.
//
// So: ask the linguists. An entry they cut through, in running text, at least
// 80% of the time and at least 20 times, is a phrase.
//
// COURSE WORDS ARE NEVER PRUNED. 36 candidates are in WORDS — ภาษาไทย,
// วันจันทร์, ที่ไหน, พวกเขา, มีความสุข — and the course teaches each as one
// vocabulary item. VISTEC's convention splits them; ours must not, or Paste
// Text would disagree with the flashcard for the same word. build-lexicon.mjs
// protects curriculum words for the same reason.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/build-seg-phrases.mjs <VISTEC train .txt>");
  process.exit(2);
}
const ROOT = new URL("..", import.meta.url).pathname;
for (const f of ["data.js", "thai-script.js", "tokeniser.js", "lexicon-th.js", "seg-extra.js", "segment.js"])
  vm.runInThisContext(readFileSync(ROOT + "web/js/" + f, "utf8"), { filename: f });
_segLoad(() => {});

const MIN_N = 20, MIN_SPLIT = 0.8;
// surface form: <msp value="X">Y</msp> keeps Y, what a reader actually meets
const clean = s => s.replace(/<msp value="[^"]*">(.*?)<\/msp>/g, "$1")
  .replace(/<\/?ne>/g, "").replace(/<\/?compound>/g, "");

const whole = new Map(), split = new Map();
for (const line of readFileSync(src, "utf8").split("\n")) {
  if (!line) continue;
  const gold = clean(line).split("|").filter(t => t !== "");
  const text = gold.join("");
  const bnd = new Set([0]);
  let p = 0;
  for (const t of gold) { p += t.length; bnd.add(p); }
  for (const t of gold) if (_segWords.has(t)) whole.set(t, (whole.get(t) || 0) + 1);
  for (let i = 0; i < text.length; i++) {
    if (!bnd.has(i)) continue;
    for (let L = Math.min(_segMaxLen, text.length - i); L >= 2; L--) {
      const w = text.substr(i, L);
      if (!_segWords.has(w) || !bnd.has(i + L)) continue;
      let cut = false;
      for (let k = i + 1; k < i + L; k++) if (bnd.has(k)) cut = true;
      if (cut) split.set(w, (split.get(w) || 0) + 1);
    }
  }
}

const course = new Set(WORDS.map(w => w[0]));
const out = [], kept = [];
for (const w of [...new Set([...whole.keys(), ...split.keys()])].sort()) {
  const kw = whole.get(w) || 0, ks = split.get(w) || 0;
  if (kw + ks < MIN_N || ks / (kw + ks) < MIN_SPLIT) continue;
  (course.has(w) ? kept : out).push(w);
}
const audited = [...new Set([...whole.keys(), ...split.keys()])]
  .filter(w => (whole.get(w) || 0) + (split.get(w) || 0) >= MIN_N).length;

writeFileSync(ROOT + "web/js/seg-phrases.js", `// AUTO-GENERATED by scripts/build-seg-phrases.mjs — do not edit by hand.
//
// Entries in lexicon-th.js that human linguists treat as MORE THAN ONE WORD.
// segment.js removes them, so ฝนตกหนัก parses ฝน|ตก|หนัก instead of ฝน|ตกหนัก
// and stops glossing heavy rain as "shoulder a burden".
//
// ${out.length} entries, each cut through in running text at least ${MIN_N} times and
// at least ${MIN_SPLIT * 100}% of the time. ${kept.length} further candidates were EXCLUDED
// because the course teaches them as vocabulary (${kept.slice(0, 6).join(", ")}…):
// Paste Text must not disagree with the flashcard about the same word.
//
// A FLOOR, NOT A VERDICT. Only ${audited} of the ${_segWords.size} lexicon entries occur
// often enough here to judge at all; the rest are unaudited, not endorsed.
//
// ── LICENCE ────────────────────────────────────────────────────────────────
// Derived from VISTEC-TP-TH-2021 by Limkonchotiwat, Phatthiyaphaibun,
// Sarwar, Chuangsuwanich and Nutanong (ACL-IJCNLP 2021),
//   https://github.com/mrpeerat/OSKut/tree/main/VISTEC-TP-TH-2021
// licensed CC BY-SA 3.0: https://creativecommons.org/licenses/by-sa/3.0/
// THIS FILE is therefore also CC BY-SA 3.0 and any redistribution must keep
// this notice. Kept separate from lexicon-th.js — which is CC0 and stays that
// way — so each file's notice is exactly true of that file and of nothing
// else, the same boundary gloss-th.js and gloss-vol.js hold.

var SEG_PHRASES = ${JSON.stringify(out.join("\n"))};
`);
console.log(`wrote web/js/seg-phrases.js — ${out.length} phrase entries`);
console.log(`  audited ${audited} of ${_segWords.size} lexicon entries (>=${MIN_N} occurrences)`);
console.log(`  excluded ${kept.length} course words: ${kept.slice(0, 8).join(" ")}…`);
